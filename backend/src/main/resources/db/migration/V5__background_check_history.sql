-- Additive migration. Apply explicitly after verifying V1/V3; no data deletion or retention job.
-- Only metadata: never store names, DOB, candidate key, input JSON or detailed result payload.
CREATE TABLE background_checks (
    request_id VARCHAR(36) PRIMARY KEY,
    employee_id VARCHAR(32) NOT NULL REFERENCES employees(employee_id),
    requested_by BIGINT NOT NULL REFERENCES user_accounts(id),
    requested_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    dispatch_deadline TIMESTAMP WITH TIME ZONE NOT NULL,
    check_id VARCHAR(128) UNIQUE,
    local_state VARCHAR(16) NOT NULL CHECK (local_state IN ('DISPATCHING','KNOWN','UNKNOWN','REJECTED','NOT_SENT')),
    status VARCHAR(16) CHECK (status IN ('pending','clear','flagged')),
    observed_at TIMESTAMP WITH TIME ZONE,
    completed_at TIMESTAMP WITH TIME ZONE,
    last_http_code INTEGER,
    last_outcome VARCHAR(40),
    poll_deadline TIMESTAMP WITH TIME ZONE NOT NULL,
    next_poll_at TIMESTAMP WITH TIME ZONE,
    poll_count INTEGER NOT NULL DEFAULT 0,
    poll_stopped BOOLEAN NOT NULL DEFAULT FALSE,
    stop_reason VARCHAR(40),
    refreshing_until TIMESTAMP WITH TIME ZONE,
    CHECK ((local_state = 'KNOWN' AND check_id IS NOT NULL AND status IS NOT NULL)
        OR (local_state <> 'KNOWN' AND check_id IS NULL AND status IS NULL))
);
CREATE INDEX background_checks_employee_time ON background_checks(employee_id, requested_at DESC);

-- Each manual detail view/reconciliation is an audit event; no cascading deletes.
CREATE TABLE background_check_views (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id VARCHAR(36) NOT NULL REFERENCES background_checks(request_id),
    viewed_by BIGINT NOT NULL REFERENCES user_accounts(id),
    viewed_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    action VARCHAR(16) NOT NULL CHECK (action IN ('DETAIL','RESOLVE')),
    status VARCHAR(16) CHECK (status IN ('pending','clear','flagged')),
    outcome VARCHAR(40) NOT NULL
);
CREATE INDEX background_check_views_request_time ON background_check_views(request_id, viewed_at DESC);
